package com.apple.foundationdb.record.query.plan.cascades;

import com.apple.foundationdb.record.query.plan.cascades.typing.Type;
import com.apple.foundationdb.record.query.plan.cascades.typing.TypeRepository;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;

/**
 * Additional tests for {@link Type} looking for edge cases.
 */
@SuppressWarnings("checkstyle:AbbreviationAsWordInName")
class TypeAutoQATest {

    @Test
    void maximumTypeOfVectorsWithDifferentDimensionsIsUndefined() {
        // BUG AQA-4: Vector.isPrimitive() is true, so maximumType returns t1 for two VECTOR types without comparing
        // precision or dimensions. Spec: Type.maximumType javadoc, "null if the maximum type is not defined".
        // maximumType must not pick one vector type for vectors whose values cannot be described by it
        final Type v1 = Type.Vector.of(false, 16, 3);
        final Type v2 = Type.Vector.of(false, 16, 5);
        assertThat(Type.maximumType(v1, v2)).isNull();
    }

    @Test
    void arrayEqualsWithErasedArrayIsSymmetric() {
        // BUG AQA-5: Array.equals calls requireNonNull(elementType) when only this side is erased, so it throws instead of
        // returning false. Spec: Object#equals contract (symmetric).
        // equals between an erased and a non-erased array must be symmetric and not throw
        final Type.Array erased = new Type.Array(false, null);
        final Type.Array typed = new Type.Array(false, Type.primitiveType(Type.TypeCode.LONG, false));
        assertThat(typed.equals(erased)).isFalse();
        assertThatCode(() -> erased.equals(typed)).doesNotThrowAnyException();
        assertThat(erased.equals(typed)).isFalse();
    }

    @Test
    void fromFieldsWithAutoGeneratedNameKeepsStorageNamesUnique() {
        // BUG AQA-6: Record.normalizeFields renames field "_1" to "_0" but keeps storage name "_1", which collides with
        // the unnamed field. Spec: Record.normalizeFields javadoc, "names and indices are consistent".
        // normalizing a field named like an auto-generated name must not produce duplicate protobuf field names
        final Type.Record record = Type.Record.fromFields(false, List.of(
                Type.Record.Field.of(Type.primitiveType(Type.TypeCode.LONG, false), Optional.of("_1")),
                Type.Record.Field.unnamedOf(Type.primitiveType(Type.TypeCode.LONG, false))));
        assertThatCode(() -> TypeRepository.newBuilder().addTypeIfNeeded(record).build())
                .doesNotThrowAnyException();
    }
}
